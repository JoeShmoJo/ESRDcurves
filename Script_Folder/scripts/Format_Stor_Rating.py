# Split the data into lines
lines = data.split("\n")

# Filter out the header rows and empty lines
lines = [line.strip() for line in lines if line.strip() and not any(char.isalpha() for char in line)]

# Extract elevation values and their respective storage values
elevation_values = []
storage_values = []

# Helper function to determine if a line starts with a number
def starts_with_number(line):
    return line and line.split()[0].isdigit()

for line in lines:
    if starts_with_number(line):
        elevation = int(line.split()[0])  # Extract elevation value
        storages = list(map(float, line.split()[1:]))  # Extract storage values as floats
        # Populate the elevation and storage lists
        for i, storage in enumerate(storages):
            elevation_values.append(elevation + i/10.0)
            storage_values.append(storage)

# Create a pandas DataFrame
df = pd.DataFrame({
    'Elev': elevation_values,
    'Stor': storage_values
})

trim_elev = 760

df = df[df['Elev'] > trim_elev]



degree = 3  # For example, change this to fit the degree you need
# Prepare your X and y data
X = df[['Elev']]
y = df['Stor']
# Create a pipeline that creates polynomial features and then fits a linear regressor
model = make_pipeline(PolynomialFeatures(degree), LinearRegression())
# Fit the model
model.fit(X, y)
# Predict using the model
df['InterpStor'] = model.predict(X)
r2_score = model.score(X, y)


# For a smooth curve, generate many points between the min and max elevation
x_plot = np.linspace(X.min(), X.max(), 1000)
# Predict on these points
y_plot = model.predict(x_plot)
# Plot the original and interpolated storage values
plt.figure(figsize=(10, 6))
# Original data points
plt.scatter(df['Elev'], df['Stor'], color='blue', label='Original Stor')
# Polynomial regression line
plt.plot(x_plot, y_plot, color='red', label='Interpolated Stor')
plt.title('Storage vs. Elevation')
plt.xlabel('Elevation')
plt.ylabel('Storage')
plt.legend()
plt.grid(True)
# Use log scale if desired
# plt.yscale('log')
# Formatter for the y-axis
plt.gca().yaxis.set_major_formatter(ScalarFormatter())
plt.show()


# Get the coefficients and intercept
coefficients = model.named_steps['linearregression'].coef_
intercept = model.named_steps['linearregression'].intercept_

# Construct the polynomial formula as a string
# Start with the intercept
formula = f"Stor = {intercept:.3f}"

# Add each term in the polynomial
for i, coef in enumerate(coefficients[1:], start=1):  # start from 1 as the first coef is for x^0
    formula += f" + {coef:.3f}*Elev^{i}"

# Print the formula
print(formula)


